def tr(language: str, key: str, **values) -> str:
    selected = language if language in TRANSLATIONS else "es"
    text = TRANSLATIONS[selected].get(key, TRANSLATIONS["es"].get(key, key))
    return text.format(**values) if values else text


def translate_runtime_message(language: str, message: str) -> str:
    if language != "en":
        return message
    return RUNTIME_MESSAGES.get(message, message)
